"""Saved portfolios in Postgres (Neon on Vercel) or a local SQLite file.

Uses plain DB-API connections, pg8000 (pure Python) for Postgres and the
standard library's sqlite3 locally, rather than an ORM: the Vercel function
has a 500 MB size limit and SQLAlchemy plus a compiled Postgres driver cost
~37 MB of it.

Every read and write goes through Store, which is bound to one signed-in
user's id; a portfolio id from another user is treated as missing.
"""
import os
import sqlite3
import ssl
from contextlib import contextmanager
from datetime import datetime, timezone
from pathlib import Path
from urllib.parse import parse_qs, unquote, urlparse

import pandas as pd

from portfolio_import import COLUMNS

LOCAL_DB = Path(__file__).parent / ".data" / "portfolios.db"

# Written for SQLite; postgres_ddl() swaps in Postgres identity columns.
SCHEMA = [
    """CREATE TABLE IF NOT EXISTS users (
        id TEXT PRIMARY KEY,
        email TEXT,
        name TEXT,
        created_at TEXT NOT NULL,
        last_seen_at TEXT NOT NULL
    )""",
    """CREATE TABLE IF NOT EXISTS portfolios (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
        name TEXT NOT NULL,
        created_at TEXT NOT NULL,
        updated_at TEXT NOT NULL,
        UNIQUE (user_id, name)
    )""",
    """CREATE TABLE IF NOT EXISTS holdings (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        portfolio_id INTEGER NOT NULL REFERENCES portfolios(id) ON DELETE CASCADE,
        position INTEGER NOT NULL,
        ticker TEXT NOT NULL,
        shares DOUBLE PRECISION NOT NULL,
        avg_price DOUBLE PRECISION,
        currency TEXT,
        account TEXT
    )""",
    # One SnapTrade user per signed-in user, its secret encrypted (brokerage_store.py). On Neon the
    # Next.js app's migrations create this table too; whichever runs first wins.
    """CREATE TABLE IF NOT EXISTS brokerage_connections (
        user_id TEXT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
        snaptrade_user_id TEXT NOT NULL,
        sealed_user TEXT NOT NULL,
        created_at TEXT NOT NULL,
        updated_at TEXT NOT NULL
    )""",
    "CREATE INDEX IF NOT EXISTS ix_portfolios_user ON portfolios (user_id)",
    "CREATE INDEX IF NOT EXISTS ix_holdings_portfolio ON holdings (portfolio_id)",
]


def postgres_ddl(statement: str) -> str:
    return (
        statement.replace("INTEGER PRIMARY KEY AUTOINCREMENT", "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
        .replace("portfolio_id INTEGER", "portfolio_id BIGINT")
    )


def database_url() -> str | None:
    """Neon's DATABASE_URL (or POSTGRES_URL) on Vercel; a local SQLite file elsewhere."""
    url = os.getenv("DATABASE_URL") or os.getenv("POSTGRES_URL")
    if url:
        return url
    if os.getenv("VERCEL"):
        return None  # no local disk worth keeping on Vercel
    LOCAL_DB.parent.mkdir(exist_ok=True)
    return f"sqlite:///{LOCAL_DB}"


def postgres_connect_args(url: str) -> dict:
    """pg8000.dbapi.connect() arguments for a postgres:// URL; SSL unless sslmode=disable."""
    parsed = urlparse(url)
    query = {k: v[0] for k, v in parse_qs(parsed.query).items()}
    args = {
        "user": unquote(parsed.username or ""),
        "password": unquote(parsed.password) if parsed.password else None,
        "host": parsed.hostname or "localhost",
        "port": parsed.port or 5432,
        "database": unquote(parsed.path.lstrip("/")) or None,
        "timeout": 15,
        "application_name": "portfolio-analyst",
    }
    if query.get("sslmode", "require") != "disable":
        args["ssl_context"] = ssl.create_default_context()
    return args


class Database:
    """Opens a connection per unit of work, which suits short-lived serverless functions."""

    def __init__(self, url: str):
        self.url = url
        if url.startswith("sqlite:///"):
            self.kind = "sqlite"
            self.path = url[len("sqlite:///"):]
        elif url.startswith(("postgres://", "postgresql://")):
            self.kind = "postgres"
            self.connect_args = postgres_connect_args(url)
        else:
            raise ValueError("DATABASE_URL must be a postgres:// or sqlite:/// URL.")

    @contextmanager
    def connect(self):
        """A connection that commits on success and rolls back on error."""
        if self.kind == "sqlite":
            conn = sqlite3.connect(self.path)
            conn.execute("PRAGMA foreign_keys = ON")
        else:
            import pg8000.dbapi

            conn = pg8000.dbapi.connect(**self.connect_args)
        try:
            yield conn
            conn.commit()
        except Exception:
            conn.rollback()
            raise
        finally:
            conn.close()

    def execute(self, conn, sql: str, params=()):
        """Run `sql` written with ? placeholders; returns the cursor."""
        if self.kind == "postgres":
            sql = sql.replace("?", "%s")
        cursor = conn.cursor()
        cursor.execute(sql, tuple(params))
        return cursor

    def create_schema(self) -> None:
        with self.connect() as conn:
            for statement in SCHEMA:
                self.execute(conn, postgres_ddl(statement) if self.kind == "postgres" else statement)


def make_engine(url: str) -> Database:
    database = Database(url)
    database.create_schema()
    return database


def _now() -> str:
    # ISO 8601 in UTC sorts correctly as text in both databases.
    return datetime.now(timezone.utc).isoformat(timespec="microseconds")


def _clean(value):
    if value is None or (isinstance(value, float) and pd.isna(value)):
        return None
    return value


class PortfolioNameError(ValueError):
    pass


class Store:
    """One user's saved portfolios."""

    def __init__(self, engine: Database, user_id: str):
        if not user_id:
            raise ValueError("A user id is required.")
        self.db = engine
        self.user_id = user_id

    def _run(self, conn, sql, params=()):
        return self.db.execute(conn, sql, params)

    def touch_user(self, email=None, name=None) -> None:
        """Create the user row on first sign-in; keep email, name and last seen current."""
        now = _now()
        with self.db.connect() as conn:
            if self._run(conn, "SELECT id FROM users WHERE id = ?", (self.user_id,)).fetchone():
                self._run(conn, "UPDATE users SET email = ?, name = ?, last_seen_at = ? WHERE id = ?",
                          (email, name, now, self.user_id))
            else:
                self._run(conn, "INSERT INTO users (id, email, name, created_at, last_seen_at) VALUES (?, ?, ?, ?, ?)",
                          (self.user_id, email, name, now, now))

    def list(self) -> list:
        """[(id, name, updated_at)], most recently updated first."""
        with self.db.connect() as conn:
            rows = self._run(
                conn,
                "SELECT id, name, updated_at FROM portfolios WHERE user_id = ? ORDER BY updated_at DESC, id DESC",
                (self.user_id,),
            ).fetchall()
        return [tuple(r) for r in rows]

    def _owned(self, conn, portfolio_id) -> bool:
        return self._run(
            conn, "SELECT id FROM portfolios WHERE id = ? AND user_id = ?", (int(portfolio_id), self.user_id)
        ).fetchone() is not None

    def save(self, name: str, table: pd.DataFrame) -> tuple[int, bool]:
        """Save `table` (COLUMNS) under `name`, replacing a portfolio of that name. Returns (id, replaced)."""
        name = _valid_name(name)
        now = _now()
        rows = []
        for i, r in enumerate(table.to_dict("records")):
            ticker = str(_clean(r.get("Ticker")) or "").strip().upper()
            shares = _clean(r.get("Shares"))
            if not ticker or shares is None:
                continue
            avg = _clean(r.get("Avg Buy Price"))
            rows.append((
                i, ticker, float(shares), None if avg is None else float(avg),
                str(_clean(r.get("Currency")) or "").strip().upper() or None,
                str(_clean(r.get("Account")) or "").strip() or None,
            ))
        with self.db.connect() as conn:
            existing = self._run(
                conn, "SELECT id FROM portfolios WHERE user_id = ? AND name = ?", (self.user_id, name)
            ).fetchone()
            if existing:
                portfolio_id = int(existing[0])
                self._run(conn, "UPDATE portfolios SET updated_at = ? WHERE id = ?", (now, portfolio_id))
                self._run(conn, "DELETE FROM holdings WHERE portfolio_id = ?", (portfolio_id,))
            else:
                portfolio_id = int(self._run(
                    conn,
                    "INSERT INTO portfolios (user_id, name, created_at, updated_at) VALUES (?, ?, ?, ?) RETURNING id",
                    (self.user_id, name, now, now),
                ).fetchone()[0])
            for row in rows:
                self._run(
                    conn,
                    "INSERT INTO holdings (portfolio_id, position, ticker, shares, avg_price, currency, account) "
                    "VALUES (?, ?, ?, ?, ?, ?, ?)",
                    (portfolio_id, *row),
                )
        return portfolio_id, existing is not None

    def load(self, portfolio_id) -> pd.DataFrame | None:
        """The portfolio's holdings as a COLUMNS table, or None if it isn't this user's."""
        with self.db.connect() as conn:
            if not self._owned(conn, portfolio_id):
                return None
            rows = self._run(
                conn,
                "SELECT ticker, shares, avg_price, currency, account FROM holdings WHERE portfolio_id = ? ORDER BY position",
                (int(portfolio_id),),
            ).fetchall()
        return pd.DataFrame(
            [{"Ticker": t, "Shares": s, "Avg Buy Price": a, "Currency": c or "", "Account": acct or ""}
             for t, s, a, c, acct in rows],
            columns=COLUMNS,
        )

    def rename(self, portfolio_id, new_name: str) -> bool:
        new_name = _valid_name(new_name)
        with self.db.connect() as conn:
            if not self._owned(conn, portfolio_id):
                return False
            clash = self._run(
                conn, "SELECT id FROM portfolios WHERE user_id = ? AND name = ? AND id <> ?",
                (self.user_id, new_name, int(portfolio_id)),
            ).fetchone()
            if clash:
                raise PortfolioNameError(f'You already have a portfolio named "{new_name}".')
            self._run(conn, "UPDATE portfolios SET name = ?, updated_at = ? WHERE id = ? AND user_id = ?",
                      (new_name, _now(), int(portfolio_id), self.user_id))
        return True

    def delete(self, portfolio_id) -> bool:
        with self.db.connect() as conn:
            if not self._owned(conn, portfolio_id):
                return False
            self._run(conn, "DELETE FROM holdings WHERE portfolio_id = ?", (int(portfolio_id),))
            self._run(conn, "DELETE FROM portfolios WHERE id = ? AND user_id = ?", (int(portfolio_id), self.user_id))
        return True

    def count(self) -> int:
        with self.db.connect() as conn:
            return int(self._run(conn, "SELECT COUNT(*) FROM portfolios WHERE user_id = ?", (self.user_id,)).fetchone()[0])


def _valid_name(name: str) -> str:
    name = (name or "").strip()
    if not name:
        raise PortfolioNameError("Give the portfolio a name.")
    if len(name) > 100:
        raise PortfolioNameError("Portfolio names can be up to 100 characters.")
    return name
